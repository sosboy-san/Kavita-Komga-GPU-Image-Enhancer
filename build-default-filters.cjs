// Build-time inspection of trusted, packaged filters; never evaluates user files.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const root=path.join(__dirname,'extension');
const dependencies=['ui/package-metadata.js','ui/parameter-schema.js','ui/analysis-contract.js','ui/module-contract.js'];
const files=['gpu/usm.js','modules/defaults/Paper-Restoration-1.0.0.js','modules/defaults/Monochrome-Line-Color-Filter-1.0.0.js'];
const items=files.map(file=>{
 const context=vm.createContext({URL,TextEncoder});
 for(const dep of dependencies)vm.runInContext(fs.readFileSync(path.join(root,dep),'utf8'),context);
 const code=fs.readFileSync(path.join(root,file),'utf8');vm.runInContext(code,context);
 const metadata=context.__KKGR_MODULE_CONTRACT__.validatePublic(context.__KKGR_MODULES__[0]);
 return {file,metadata,checksum:crypto.createHash('sha256').update(code).digest('hex')};
});
fs.writeFileSync(path.join(root,'modules/default-filters.js'),'// Generated by build-default-filters.cjs from packaged filter sources.\n'+
 'globalThis.__KKGR_DEFAULT_FILTERS__='+JSON.stringify(items)+';\n');
console.log('Built metadata for '+items.length+' removable default filters');
